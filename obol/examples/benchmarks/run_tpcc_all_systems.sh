#!/bin/bash
# Runs the TPC-C saturation sweep for every system, including the Obol
# optimization ablation study, and stores one result file per
# (system, warehouse-count, offered-throughput) point.
#
# Typical cluster invocation (from anywhere):
#   nohup bash obol/examples/benchmarks/run_tpcc_all_systems.sh results 80 60 30 10 > tpcc_logs.log 2>&1 &
#
# Usage:
#   bash run_tpcc_all_systems.sh [SAVING_DIR] [PARTITIONS] [EXP_TIME] [WARMUP] [STYX_THREADS_PER_WORKER] [SYSTEM ...]
#
# SYSTEM (optional, defaults to all of them):
#   handwritten     hand-written Styx operators (baseline)
#   obol_gather     Obol, all optimizations on (the full system)
#   obol_nogather   ablation: sequential dispatch instead of gather fan-out
#   obol_no_tco     ablation: no distributed tail-call optimization
#   obol_ctx_net    ablation: live context shipped through the network in
#                   reply_to instead of being saved in the operator's state
#   obol_no_live    ablation: full defined-variable capture (no live-variable
#                   analysis minimizing the serialized context)
#
# Every ablation variant disables exactly one optimization relative to
# obol_gather, so (obol_gather - variant) isolates that optimization's
# contribution. The compiled variants are generated by
# obol/examples/benchmarks/compile_variants.py and are checked in under
# demo/demo-tpc-c/functions/.
#
# Result files land in SAVING_DIR as tpcc_<system>_W<warehouses>_<tput>_ALL.json;
# already-existing points are skipped, so the sweep is resumable and can be
# extended by simply re-running this script.
#
# Deployment mode (docker-compose | k8s-minikube | k8s-cluster) is inherited
# from the environment exactly as in scripts/run_batch_experiments.sh.

set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
cd "$REPO_ROOT"

SAVING_DIR=${1:-results}
PARTITIONS=${2:-4}
EXP_TIME=${3:-60}
WARMUP=${4:-30}
STYX_THREADS_PER_WORKER=${5:-1}
shift $(( $# < 5 ? $# : 5 ))

DEFAULT_SYSTEMS=(handwritten obol_gather obol_nogather obol_no_tco obol_ctx_net obol_no_live)
if [ $# -gt 0 ]; then
    SYSTEMS=("$@")
else
    SYSTEMS=("${DEFAULT_SYSTEMS[@]}")
fi

CONFIG_CSV="scripts/styx_experiments_config.csv"
N_KEYS=10  # ignored for tpcc (warehouse counts come from create_config.py)

# system token -> compiled variant loaded by demo/demo-tpc-c/graph_compiled.py
# (handwritten does not use a compiled variant; run_experiment.sh selects the
# hand-written demo whenever TPCC_SYSTEM does not start with "obol").
variant_for() {
    case "$1" in
        handwritten)   echo gather ;;   # unused, but keep the env var valid
        obol_gather)   echo gather ;;
        obol_nogather) echo no_gather ;;
        obol_no_tco)   echo no_tco ;;
        obol_ctx_net)  echo ctx_net ;;
        obol_no_live)  echo no_live ;;
        *)             return 1 ;;
    esac
}

for system in "${SYSTEMS[@]}"; do
    if ! variant_for "$system" > /dev/null; then
        echo "ERROR: unknown system '$system' (expected: ${DEFAULT_SYSTEMS[*]})" >&2
        exit 1
    fi
done

mkdir -p "$SAVING_DIR"

run_system() {
    local system=$1
    local variant
    variant="$(variant_for "$system")"
    echo
    echo "############################################################"
    echo "# SYSTEM: $system   (compiled variant: $variant)"
    echo "############################################################"
    export TPCC_SYSTEM="$system"
    export TPCC_COMPILED_VARIANT="$variant"

    ./scripts/run_batch_experiments.sh \
        "$CONFIG_CSV" \
        "$SAVING_DIR" \
        "$STYX_THREADS_PER_WORKER" \
        "$PARTITIONS" \
        "$N_KEYS" \
        "$EXP_TIME" \
        "$WARMUP" \
        tpcc
}

for system in "${SYSTEMS[@]}"; do
    run_system "$system"
done

echo
echo "ALL TPC-C SYSTEMS DONE (${SYSTEMS[*]}) -> $SAVING_DIR"
